#!/usr/bin/env python3
"""Print the lookup tables of runtime/minyar_crc_tables.h.

    python3 tools/generate-crc-tables.py > runtime/minyar_crc_tables.h

Two reflected polynomials are tabulated for slicing-by-8:
  * CRC-32/ISO-HDLC (IEEE 802.3, zip, gzip, PNG): reflected 0xEDB88320.
  * CRC-64/NVME (the variant minyar-objstore's src/crc64.c implements):
    reflected 0x9A6C9329AC4BC9B5, init/xorout all ones.
Table k of a width holds the effect of k zero bytes after a byte step, so a
table-driven loop consumes eight input bytes per stride.
"""

CRC32_POLY = 0xEDB88320
CRC64_POLY = 0x9A6C9329AC4BC9B5


def byte_table(poly, bits):
    mask = (1 << bits) - 1

    def step(c):
        for _ in range(8):
            c = (c >> 1) ^ poly if c & 1 else c >> 1
        return c

    return [step(i) for i in range(256)], mask


def slices(table, mask):
    result = [table]
    for _ in range(1, 8):
        previous = result[-1]
        result.append([(value >> 8) ^ table[value & 0xFF] for value in previous])
    return result


def emit(name, width, rows):
    print(f"static const uint{width}_t {name}[8][256] = {{")
    for row in rows:
        print("    {")
        for start in range(0, 256, 6):
            values = ", ".join(f"UINT{width}_C(0x{value:0{width // 4}x})" for value in row[start:start + 6])
            print(f"        {values},")
        print("    },")
    print("};")


def main():
    print("/* Generated by tools/generate-crc-tables.py. Do not edit by hand. */")
    thirty_two = slices(*byte_table(CRC32_POLY, 32))
    sixty_four = slices(*byte_table(CRC64_POLY, 64))
    emit("crc32_slices", 32, thirty_two)
    emit("crc64_slices", 64, sixty_four)


if __name__ == "__main__":
    main()
