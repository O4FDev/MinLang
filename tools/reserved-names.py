#!/usr/bin/env python3
"""Generate/check the reserved function names section of docs/language.md from compiler predicates."""
import argparse
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / 'docs/language.md'
BEGIN = '<!-- reserved-names: generated by tools/reserved-names.py -->\n'
END = '<!-- reserved-names: end -->\n'


def names():
    source = runpy.run_path(str(ROOT / 'compiler/source.py'))['core_source']()
    found = set()
    for function in ('isBuiltinName', 'isNumericBuiltin', 'isFloatFunction'):
        body = re.search(r'^function ' + function + r'\([^\n]+\{\n(.*?)\n}', source, re.M | re.S)
        if body is None:
            raise ValueError('missing compiler predicate ' + function)
        found.update(re.findall(r'name == "([A-Za-z_][A-Za-z_0-9]*)"', body[1]))
    return sorted(found)


def render():
    return '''## Reserved function names

These names belong to the language's built-in functions and constructors.
A user function cannot declare one of them, including inside an imported
module. Choose a different function name, such as `joinTextLocal` or `joinWith`.
Record fields and methods use their receiver's namespace; this list reserves
function declarations, not field names or arbitrary prefixes.

Names are case-sensitive. Standard-library functions belong to their module
alias and do not reserve every module's function namespace.

| Reserved function name |
| --- |
''' + ''.join(f'| `{name}` |\n' for name in names()) + '''
Generated from the compiler by `python3 tools/reserved-names.py`.
Run `python3 tools/reserved-names.py --check` after changing built-in names.
'''


def section(document):
    """The generated section of the language reference, or None."""
    if BEGIN not in document or END not in document:
        return None
    return document.split(BEGIN, 1)[1].split(END, 1)[0]


def published(document):
    """The document with its generated section replaced, or appended at the end."""
    if section(document) is None:
        return document.rstrip('\n') + '\n\n' + BEGIN + render() + END
    before, rest = document.split(BEGIN, 1)
    return before + BEGIN + render() + END + rest.split(END, 1)[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    document = DOCUMENT.read_text()
    if args.check:
        if section(document) != render():
            parser.exit(1, 'reserved-name list is stale; run python3 tools/reserved-names.py\n')
    else:
        DOCUMENT.write_text(published(document))


if __name__ == '__main__': main()
