#!/usr/bin/env python3
"""Print runtime/minyar_pow10_table.h, the 128-bit powers of ten used by
runtime/minyar_float_scale.h for Float printing and decimal parsing.

    python3 tools/generate-pow10-table.py > runtime/minyar_pow10_table.h
    python3 tools/generate-pow10-table.py --check runtime/minyar_pow10_table.h

Entry p (POW10_MIN <= p <= POW10_MAX) describes pm = ceil(10^p * 2^b), where
the integer b puts pm in [2^127, 2^128). It is stored as (hi, lo) with
pm = hi * 2^64 - lo, so hi alone is pm rounded up to its top 64 bits. This is
the table of Russ Cox's rsc.io/fpfmt pow10gen.go, computed here with exact
Python integers.
"""
import sys

POW10_MIN = -348
POW10_MAX = 347


def entry(p):
    if p >= 0:
        numerator, denominator = 10**p, 1
    else:
        numerator, denominator = 1, 10**-p
    # Choose b with 2^127 <= 10^p * 2^b < 2^128.
    b = 127 - (numerator.bit_length() - denominator.bit_length())
    while True:
        scaled_n = numerator << b if b >= 0 else numerator
        scaled_d = denominator if b >= 0 else denominator << -b
        if scaled_n < scaled_d << 127:
            b += 1
        elif scaled_n >= scaled_d << 128:
            b -= 1
        else:
            break
    pm = -(-scaled_n // scaled_d)  # ceiling
    assert 1 << 127 <= pm < 1 << 128, p
    hi = -(-pm >> 64)
    lo = (hi << 64) - pm
    assert 0 <= lo < 1 << 64 and hi < 1 << 64 and (hi << 64) - lo == pm
    return hi, lo, b


def render():
    lines = [
        "/* Generated by tools/generate-pow10-table.py. Do not edit by hand.",
        " * Entry p - POW10_MIN is {hi, lo} with hi * 2^64 - lo = ceil(10^p * 2^b),",
        " * scaled into [2^127, 2^128). */",
        f"enum {{ POW10_MIN = {POW10_MIN}, POW10_MAX = {POW10_MAX} }};",
        f"static const uint64_t minyar_pow10_table[{POW10_MAX - POW10_MIN + 1}][2] = {{",
    ]
    for p in range(POW10_MIN, POW10_MAX + 1):
        hi, lo, b = entry(p)
        lines.append(f"    {{UINT64_C(0x{hi:016x}), UINT64_C(0x{lo:016x})}}, /* 1e{p} * 2^{b} */")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        with open(sys.argv[2], encoding="utf-8") as existing:
            if existing.read() != text:
                sys.exit(sys.argv[2] + " differs from tools/generate-pow10-table.py output")
        print("pow10 table matches its generator")
        return
    if len(sys.argv) != 1:
        sys.exit("usage: generate-pow10-table.py [--check FILE]")
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
