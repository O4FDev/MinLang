#!/bin/sh
# Standalone installer. prepare-release.py embeds the public key and host.
set -eu
umask 077
LC_ALL=C
export LC_ALL
unset TAR_OPTIONS
embedded_key='@MINYAR_RELEASE_KEY@'
embedded_server='@MINYAR_DIST_URL@'
version=latest
server=${MINYAR_DIST_URL:-$embedded_server}
minyar_home=${MINYAR_HOME:-${HOME:?HOME must be set}/.minyar}
set_default=1
welcome=1
temporary=
staging=
lock=
die() { printf 'minyar: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*" >&2; }
cleanup() {
    [ -z "$temporary" ] || rm -rf -- "$temporary"
    [ -z "$staging" ] || rm -rf -- "$staging"
    [ -z "$lock" ] || rmdir -- "$lock" 2>/dev/null || :
}
trap cleanup 0
trap 'exit 130' INT
trap 'exit 143' TERM HUP
valid_version() {
    [ "${#1}" -le 80 ] || return 1
    case "$1" in ''|*[!0-9A-Za-z.+-]*|*..*) return 1 ;; esac
    awk -v version="$1" 'BEGIN { exit !(version ~ /^[0-9]+\.[0-9]+\.[0-9]+([+-][0-9A-Za-z.-]+)?$/) }'
}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --version|--server|--home)
            [ "$#" -ge 2 ] || die "$1 requires a value"
            case "$1" in --version) version=$2 ;; --server) server=$2 ;; --home) minyar_home=$2 ;; esac
            shift 2 ;;
        --no-default) set_default=0; shift ;;
        --help|-h)
            printf 'Install Minyar: sh install [--version VERSION] [--server URL] [--home DIR] [--no-default]\n'
            exit 0 ;;
        *) die "unknown installer option: $1" ;;
    esac
done
[ ! -f "$minyar_home/.minyar-home" ] || welcome=0
[ "$version" = latest ] || valid_version "$version" || die 'toolchain versions use MAJOR.MINOR.PATCH, optionally with a prerelease suffix'
case "$server" in
    https://*) ;;
    http://127.0.0.1:*)
        authority=${server#http://}; authority=${authority%%/*}; test_port=${authority#127.0.0.1:}
        case "$test_port" in ''|*[!0-9]*) die 'HTTP is permitted only for a numeric loopback test server' ;; esac ;;
    *) die 'set MINYAR_DIST_URL to an HTTPS release host (or use --server); this source template is not a published installer' ;;
esac
case "$server" in *[\ \	\
\'\"\`\$\#\?]*) die 'release server URL contains unsupported characters' ;; esac
server=${server%/}
for command in curl tar awk ssh-keygen mktemp; do command -v "$command" >/dev/null 2>&1 || die "$command is required; install it and repeat this command"; done
if command -v sha256sum >/dev/null 2>&1; then hash_command=sha256sum
elif command -v shasum >/dev/null 2>&1; then hash_command=shasum
else die 'SHA-256 verification needs sha256sum or shasum'; fi
case "$(uname -s)" in
    Darwin)
        operating_system=macos
        macos_version=$(sw_vers -productVersion); macos_major=${macos_version%%.*}
        [ "$macos_major" -ge 14 ] || die "Minyar requires macOS 14 or newer (found $macos_version)"
        if [ "${SDKROOT+x}" = x ]; then sdk=$SDKROOT
        else sdk=$(xcrun --show-sdk-path 2>/dev/null) || die 'the Apple SDK is missing; run xcode-select --install, finish installation, then repeat this command'; fi
        [ -d "$sdk" ] || die 'the Apple SDK is unavailable; unset stale SDKROOT/DEVELOPER_DIR overrides or run xcode-select --install, then repeat this command' ;;
    Linux) operating_system=linux ;;
    *) die 'this installer supports macOS and Linux' ;;
esac
architecture=$(uname -m)
if [ "$operating_system" = macos ] && [ "$(/usr/sbin/sysctl -n sysctl.proc_translated 2>/dev/null || :)" = 1 ]; then architecture=arm64; fi
case "$architecture" in arm64|aarch64) architecture=arm64 ;; x86_64|amd64) architecture=x86_64 ;; *) die "unsupported processor: $architecture" ;; esac
temporary=$(mktemp -d "${TMPDIR:-/tmp}/minyar-install.XXXXXXXX")
temporary=$(CDPATH= cd -- "$temporary" && pwd -P)
key=$embedded_key
if [ "${key#@}" != "$key" ]; then
    trusted_key=${MINYAR_TRUSTED_KEY:-$minyar_home/release-key.pub}
    [ -f "$trusted_key" ] || die 'release signing key is not configured; use an installer generated by install/prepare-release.py'
    key=$(cat -- "$trusted_key")
fi
case "$key" in 'ssh-ed25519 '*) ;; *) die 'the release signing key must be an Ed25519 OpenSSH public key' ;; esac
printf '%s\n' "$key" > "$temporary/release-key.pub"
ssh-keygen -l -f "$temporary/release-key.pub" >/dev/null 2>&1 || die 'invalid release signing key'
printf 'minyar-release namespaces="toolchain@minyar" %s\n' "$key" > "$temporary/allowed-signers"
download() {
    curl -q --fail --silent --show-error --location --connect-timeout 15 --max-time 600 --max-filesize "$3" --proto '=http,https' --proto-redir '=https' --output "$2" -- "$1" || die "download failed: $1; check the release host and repeat this command"
}
verify_signature() {
    ssh-keygen -Y verify -f "$temporary/allowed-signers" -I minyar-release -n toolchain@minyar -s "$1.sig" < "$1" > "$temporary/signature.log" 2>&1 || die 'release signature verification failed; nothing was installed'
}
if [ "$version" = latest ]; then
    download "$server/latest" "$temporary/latest" 1024
    download "$server/latest.sig" "$temporary/latest.sig" 65536
    verify_signature "$temporary/latest"
    version=$(cat -- "$temporary/latest")
    valid_version "$version" || die 'the signed latest release has an invalid version'
fi
artifact="minyar-$version-$operating_system-$architecture"
archive="$artifact.tar.gz"
say "  Fetching  Minyar $version · $operating_system-$architecture"
download "$server/releases/$version/SHA256SUMS" "$temporary/SHA256SUMS" 1048576
download "$server/releases/$version/SHA256SUMS.sig" "$temporary/SHA256SUMS.sig" 65536
verify_signature "$temporary/SHA256SUMS"
expected=$(awk -v name="$archive" '$2 == name { found++; value=$1 } END { if (found != 1) exit 1; print value }' "$temporary/SHA256SUMS") || die "no signed artifact exists for $operating_system-$architecture at $version"
case "$expected" in *[!0-9a-f]*|'') die 'invalid SHA-256 in the signed release manifest' ;; esac
[ "${#expected}" -eq 64 ] || die 'invalid SHA-256 length in the signed release manifest'
download "$server/releases/$version/$archive" "$temporary/$archive" 2147483648
if [ "$hash_command" = sha256sum ]; then actual=$(sha256sum "$temporary/$archive"); else actual=$(shasum -a 256 "$temporary/$archive"); fi
actual=${actual%% *}
[ "$actual" = "$expected" ] || die 'archive checksum mismatch; nothing was installed'
say '  Verified  Ed25519 signature + SHA-256'
tar -tzf "$temporary/$archive" > "$temporary/paths" || die 'cannot read the toolchain archive'
awk -v root="$artifact" '{ path=$0; if (path !~ /^[A-Za-z0-9_.\/+@-]+$/ || path ~ /(^|\/)\.\.(\/|$)/ || (path != root && path != root "/" && index(path,root "/") != 1)) bad=1 } END { exit bad }' "$temporary/paths" || die 'archive contains unsafe paths'
tar -tvzf "$temporary/$archive" > "$temporary/entries" || die 'cannot inspect the toolchain archive'
awk '{ kind=substr($0,1,1); if (kind != "-" && kind != "d" && kind != "l") bad=1; if (kind == "l" && ($(NF-1) != "->" || $NF !~ /^[A-Za-z0-9_.\/+@-]+$/ || $NF ~ /^\// || $NF ~ /(^|\/)\.\.(\/|$)/)) bad=1 } END { exit bad }' "$temporary/entries" || die 'archive contains unsupported links or special files'
mkdir -p -- "$minyar_home"
minyar_home=$(CDPATH= cd -- "$minyar_home" && pwd -P)
if [ -e "$minyar_home/.minyar-home" ] || [ -L "$minyar_home/.minyar-home" ]; then
    [ ! -L "$minyar_home/.minyar-home" ] && [ "$(cat -- "$minyar_home/.minyar-home")" = minyar-home-v1 ] || die 'refusing to use an unrelated installation marker'
else
    for name in manager.sh toolchains default release-key.pub server; do [ ! -e "$minyar_home/$name" ] && [ ! -L "$minyar_home/$name" ] || die "refusing to replace an unrelated $minyar_home/$name"; done
fi
if [ -e "$minyar_home/bin/minyar" ] || [ -L "$minyar_home/bin/minyar" ]; then
    [ ! -L "$minyar_home/bin/minyar" ] && [ -f "$minyar_home/bin/minyar" ] && grep -Fqx '# Managed by Minyar toolchains (v1)' "$minyar_home/bin/minyar" || die "refusing to replace an unrelated command: $minyar_home/bin/minyar"
fi
if [ -f "$minyar_home/release-key.pub" ]; then [ "$(cat -- "$minyar_home/release-key.pub")" = "$key" ] || die 'the release signing key differs from this installation; review the new key before reinstalling'; fi
mkdir -- "$minyar_home/.install-lock" 2>/dev/null || die 'another toolchain installation is running; repeat this command when it finishes'
lock=$minyar_home/.install-lock
mkdir -p -- "$minyar_home/toolchains" "$minyar_home/bin"
for name in toolchains bin manager.sh default release-key.pub server; do [ ! -L "$minyar_home/$name" ] || die "installation entries cannot be symlinks: $name"; done
destination=$minyar_home/toolchains/$version
if [ -e "$destination" ] || [ -L "$destination" ]; then
    [ ! -L "$destination" ] && [ -f "$destination/.minyar-toolchain" ] && [ "$(cat -- "$destination/.minyar-toolchain")" = "$version" ] || die "refusing to replace an unrelated toolchain: $destination"
    [ "$(cat -- "$destination/.minyar-archive-sha256")" = "$expected" ] || die 'this version is already installed with a different archive; release versions must be immutable'
else
    staging=$(mktemp -d "$minyar_home/toolchains/.install-XXXXXXXX")
    tar --no-same-owner --no-same-permissions -xzf "$temporary/$archive" -C "$staging" || die 'toolchain extraction failed'
    staged=$staging/$artifact
    for name in minyar install/manager.sh install/install.sh; do [ -f "$staged/$name" ] && [ ! -L "$staged/$name" ] || die "archive is missing $name; rebuild it with the current Minyar packager"; done
    [ -x "$staged/minyar" ] || die 'the toolchain launcher is not executable'
    if [ -f "$staged/distribution.version" ]; then [ "$(cat -- "$staged/distribution.version")" = "$version" ] || die 'archive version metadata disagrees with its name'; fi
    if [ -f "$staged/distribution.arch" ]; then [ "$(cat -- "$staged/distribution.arch")" = "$architecture" ] || die 'archive architecture metadata disagrees with its name'; fi
    "$staged/minyar" --version > "$temporary/version.log" 2>&1 || die 'the verified toolchain could not start; the previous installation is unchanged'
    printf '%s\n' "$version" > "$staged/.minyar-toolchain"
    printf '%s\n' "$expected" > "$staged/.minyar-archive-sha256"
    mv -- "$staged" "$destination"
fi
printf 'minyar-home-v1\n' > "$minyar_home/.minyar-home"
cp -- "$destination/install/manager.sh" "$minyar_home/.manager-$$"
chmod 755 "$minyar_home/.manager-$$"
mv -f -- "$minyar_home/.manager-$$" "$minyar_home/manager.sh"
printf '%s\n' "$key" > "$minyar_home/.key-$$"; mv -f -- "$minyar_home/.key-$$" "$minyar_home/release-key.pub"
printf '%s\n' "$server" > "$minyar_home/.server-$$"; mv -f -- "$minyar_home/.server-$$" "$minyar_home/server"
if [ "$set_default" -eq 1 ] || [ ! -f "$minyar_home/default" ]; then printf '%s\n' "$version" > "$minyar_home/.default-$$"; mv -f -- "$minyar_home/.default-$$" "$minyar_home/default"; fi
cat > "$minyar_home/bin/.minyar-$$" <<'SHIM'
#!/bin/sh
# Managed by Minyar toolchains (v1)
set -eu
MINYAR_HOME=${MINYAR_HOME:-$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)}
export MINYAR_HOME
exec sh "$MINYAR_HOME/manager.sh" "$@"
SHIM
chmod 755 "$minyar_home/bin/.minyar-$$"
mv -f -- "$minyar_home/bin/.minyar-$$" "$minyar_home/bin/minyar"
say " Installed  Minyar $version"
if [ "$welcome" -eq 1 ]; then
    say ""
    say 'Minyar is ready.'
    quoted_path=$(printf '%s' "$minyar_home/bin" | sed "s/'/'\\\"'\\\"'/g")
    say "  export PATH='$quoted_path':\"\$PATH\""
    say '  minyar new hello && cd hello && minyar run'
fi
