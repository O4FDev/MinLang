static uint64_t crc32c_load64(const unsigned char *p) {
    uint64_t word;
    memcpy(&word, p, 8);
#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_BIG_ENDIAN__
    word = __builtin_bswap64(word);
#endif
    return word;
}

static uint32_t crc32c_software(uint32_t crc, const unsigned char *p, size_t n) {
    while (n && ((uintptr_t)p & 7)) {
        crc = crc32c_slices[0][(crc ^ *p++) & 0xFF] ^ (crc >> 8);
        n--;
    }
    while (n >= 8) {
        uint64_t word = crc32c_load64(p) ^ crc;
        crc = crc32c_slices[7][word & 0xFF] ^ crc32c_slices[6][(word >> 8) & 0xFF] ^
              crc32c_slices[5][(word >> 16) & 0xFF] ^ crc32c_slices[4][(word >> 24) & 0xFF] ^
              crc32c_slices[3][(word >> 32) & 0xFF] ^ crc32c_slices[2][(word >> 40) & 0xFF] ^
              crc32c_slices[1][(word >> 48) & 0xFF] ^ crc32c_slices[0][word >> 56];
        p += 8;
        n -= 8;
    }
    while (n--)
        crc = crc32c_slices[0][(crc ^ *p++) & 0xFF] ^ (crc >> 8);
    return crc;
}

#if defined(MINYAR_CRC32C_X86) || defined(MINYAR_CRC32C_ARM)
static uint32_t crc32c_shift(const uint32_t table[4][256], uint32_t crc) {
    return table[0][crc & 0xFF] ^ table[1][(crc >> 8) & 0xFF] ^ table[2][(crc >> 16) & 0xFF] ^
           table[3][crc >> 24];
}
/* The instructions are inline assembly rather than target builtins: release builds strip target attributes from
 * the runtime's IR so it can be inlined into Minyar code, and a builtin then has no instruction to select. */
#if defined(MINYAR_CRC32C_X86)
static inline uint64_t crc32c_word(uint64_t crc, uint64_t word) {
    __asm__("crc32q %1, %0" : "+r"(crc) : "rm"(word));
    return crc;
}
static inline uint32_t crc32c_byte(uint32_t crc, unsigned char byte) {
    __asm__("crc32b %1, %0" : "+r"(crc) : "rm"(byte));
    return crc;
}
#else
static inline uint64_t crc32c_word(uint64_t crc, uint64_t word) {
    uint32_t value = (uint32_t)crc;
    __asm__(".arch_extension crc\n\tcrc32cx %w0, %w0, %x1" : "+r"(value) : "r"(word));
    return value;
}
static inline uint32_t crc32c_byte(uint32_t crc, unsigned char byte) {
    __asm__(".arch_extension crc\n\tcrc32cb %w0, %w0, %w1" : "+r"(crc) : "r"((uint32_t)byte));
    return crc;
}
#endif
/* Three chains of `block` bytes each hide the instruction's latency; the register update is linear over GF(2),
 * so the register after A ++ B is shift_|B|(register after A) xor (register of B started from zero). */
static uint32_t crc32c_blocks(uint32_t crc, const unsigned char **next, size_t *n, size_t block,
                                            const uint32_t shift[4][256]) {
    const unsigned char *p = *next;
    while (*n >= 3 * block) {
        uint64_t a = crc, b = 0, c = 0;
        const unsigned char *end = p + block;
        do {
            a = crc32c_word(a, crc32c_load64(p));
            b = crc32c_word(b, crc32c_load64(p + block));
            c = crc32c_word(c, crc32c_load64(p + 2 * block));
            p += 8;
        } while (p < end);
        crc = crc32c_shift(shift, (uint32_t)a) ^ (uint32_t)b;
        crc = crc32c_shift(shift, crc) ^ (uint32_t)c;
        p += 2 * block;
        *n -= 3 * block;
    }
    *next = p;
    return crc;
}
static uint32_t crc32c_hardware(uint32_t crc, const unsigned char *p, size_t n) {
    while (n && ((uintptr_t)p & 7)) {
        crc = crc32c_byte(crc, *p++);
        n--;
    }
    crc = crc32c_blocks(crc, &p, &n, CRC32C_LONG, crc32c_long_shift);
    crc = crc32c_blocks(crc, &p, &n, CRC32C_SHORT, crc32c_short_shift);
    uint64_t wide = crc;
    while (n >= 8) {
        wide = crc32c_word(wide, crc32c_load64(p));
        p += 8;
        n -= 8;
    }
    crc = (uint32_t)wide;
    while (n--)
        crc = crc32c_byte(crc, *p++);
    return crc;
}
static int crc32c_support; /* 0 unknown, 1 hardware, 2 software; atomic builtins */
static int crc32c_detect(void) {
#if defined(MINYAR_CRC32C_X86)
#if defined(__SSE4_2__)
    return 1;
#else
    unsigned eax, ebx, ecx, edx;
    return __get_cpuid(1, &eax, &ebx, &ecx, &edx) && (ecx & (1u << 20)) ? 1 : 2;
#endif
#elif defined(__ARM_FEATURE_CRC32) || defined(__APPLE__)
    return 1;
#elif defined(__linux__) && defined(__STDC_HOSTED__) && __STDC_HOSTED__ && defined(HWCAP_CRC32)
    return getauxval(AT_HWCAP) & HWCAP_CRC32 ? 1 : 2;
#else
    return 2;
#endif
}
#endif

static uint32_t crc32c_update(uint32_t crc, const unsigned char *p, size_t n) {
    crc = ~crc;
#if defined(MINYAR_CRC32C_X86) || defined(MINYAR_CRC32C_ARM)
    int support = __atomic_load_n(&crc32c_support, __ATOMIC_RELAXED);
    if (!support) {
        support = crc32c_detect();
        __atomic_store_n(&crc32c_support, support, __ATOMIC_RELAXED);
    }
    crc = support == 1 ? crc32c_hardware(crc, p, n) : crc32c_software(crc, p, n);
#else
    crc = crc32c_software(crc, p, n);
#endif
    return ~crc;
}

/* checksum.crc32c(crc, data, offset, length): the CRC32C of data[offset, offset + length) continuing crc (the
 * low 32 bits; 0 starts a new checksum). An out-of-range request stops like a Bytes getter. */
long long minyar_runtime_crc32c(long long crc, const MinyarBytes *data, long long offset, long long length) {
    if (offset < 0 || length < 0 || offset > data->byte_length || length > data->byte_length - offset) {
        char message[160];
        snprintf(message, sizeof(message),
                 "a CRC32C range of %lld bytes at position %lld does not fit in Bytes of length %lld.",
                 length, offset, data->byte_length);
        minyar_stop_program(message);
    }
    return (long long)crc32c_update((uint32_t)crc, data->bytes + offset, (size_t)length);
}
